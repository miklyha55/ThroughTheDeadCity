import * as THREE from 'three';
import { CONFIG } from '../config.js';
import { listener, resumeAudio } from './audio.js';

const CFG = CONFIG.startMessage;

/**
 * Вступительное сообщение: голос, с которого начинается первый уровень.
 *
 * Говорит он фоном: управление при этом не отбирается, и город можно
 * осматривать с первых слов. Замок тут стоял и был снят намеренно — полминуты
 * неподвижности в начале игры отнимались у игрока целиком, и дослушивал он их
 * стоя. `locked` остался и нужен по-прежнему: по нему висит рация и по нему же
 * `Escape` отдаётся пропуску речи, а не паузе.
 *
 * Ждёт первого действия игрока. Сперва он видит подсказку по управлению, и
 * только когда тронется с места — по рации начинают говорить. Одно движение и
 * снимает подсказку, и пускает речь.
 *
 * Заодно это снимает старую заботу о звуке: браузер не даёт его до первого
 * жеста, а тут жест уже случился.
 *
 * На телефоне речь пропускается касанием, на клавиатуре — Escape.
 *
 * Звучит один раз за сеанс. Смерть на первом уровне — дело обычное, и слушать
 * одну и ту же речь после каждой перезагрузки уровня было бы наказанием.
 *
 * Если звук не завёлся — файла нет, браузер отказал, дорожка зависла, —
 * сообщение тихо объявляет себя отговорившим и ничего не держит.
 */
export class StartMessage {
  /** @param {import('../ui/Transmission.js').Transmission} [text] — субтитры */
  constructor(text = null) {
    this.text = text;
    this.onDone = null;  // кому сказать, что вступление кончилось
    this.onSpeak = null; // и что оно началось: сноске о пропуске
    this.onArm = null;   // и что оно взведено и ждёт первого действия
    this.onStop = null;  // и что оборвалось на полуслове: ей же
    this.audio = new Audio(CFG.file);
    this.audio.preload = 'auto';

    // Голос идёт через того же слушателя, что и всё остальное. Источник
    // потоковый, а не разобранный в память: субтитры печатаются по
    // `currentTime` самой дорожки, и элемент тут нужен как таковой.
    this.voice = new THREE.Audio(listener);
    this.voice.setMediaElementSource(this.audio);
    this.voice.setVolume(CFG.volume);

    this.state = 'idle'; // idle → armed (ждём касание) → speaking → done
    this.played = false;
    this.muted = false;  // выключено в панели разработчика: логика не запускается вовсе
    this.start = this.start.bind(this);
    this._timer = null;

    // Пропуск. Речь длинная, а при отладке и на втором прохождении слушать её
    // незачем — но и снимать совсем нельзя: тому, кто пришёл впервые, она и
    // рассказывает, куда идти.
    addEventListener('keydown', (event) => {
      if (event.code === CFG.skipKey && this.locked) this.skip();
    });
  }

  /**
   * Речь на ходу: либо ещё ждём первого касания, либо голос уже говорит.
   *
   * Управление это больше не отбирает. По этому признаку висит рация в углу и
   * ему же отдаётся `Escape` — там он пропускает речь, а не ставит паузу.
   */
  get locked() {
    return this.state === 'armed' || this.state === 'speaking';
  }

  /**
   * Поставить сообщение на уровень. На остальных — и на повторном заходе
   * на первый — молчит.
   *
   * @param {number} level — номер уровня из его файла
   */
  arm(level) {
    if (this.muted || this.played || level !== CFG.level) return;

    this.state = 'armed';
    this.onArm?.(); // уровень открылся и ждёт игрока — самое время объяснить управление

    /**
     * Ждём первого действия игрока, всегда.
     *
     * Раньше, если разрешение на звук уже было дано кнопкой «Играть», голос
     * заговаривал сам, в тот же миг, как открылся уровень. Теперь порядок
     * другой: сперва игрок видит, как управлять, и только когда он тронется с
     * места — по рации начинают говорить. Одно его движение и снимает
     * подсказку, и пускает речь.
     *
     * Слушаем и касание, и мышь, и клавиши: на столе экрана касаться нечем.
     */
    for (const event of ['pointerdown', 'touchstart', 'keydown']) {
      addEventListener(event, this.start, { once: true });
    }
  }

  /** Пустить голос: игрок впервые тронулся с места. */
  start() {
    if (this.state !== 'armed') return;

    this.state = 'speaking';
    this.played = true;
    this.onSpeak?.(); // речь пошла — можно сказать, что её разрешено пропустить

    // Дорожка звучит через общий граф, а спящий контекст его не выпускает
    // наружу. Поднимаем отсюда: сюда мы попали из обработчика касания.
    resumeAudio();

    this.audio.addEventListener('ended', () => this._release(), { once: true });
    this.audio.addEventListener('error', () => this._release(), { once: true });

    // Предохранитель: дорожка может не доиграть до конца и не сказать об этом —
    // вкладку свернули, звук не отдали. Речь закроется по времени.
    this._timer = setTimeout(() => this._release(), CFG.maxLock * 1000);

    this.text?.start(this.audio); // текст идёт за дорожкой, а не за таймером

    // Браузер отказал — не держим игрока. И не считаем речь состоявшейся:
    // отказ означает, что её не слышали вовсе, а `played` запретил бы ей
    // завестись потом, когда звук разрешат. Уровень начнётся молча, зато
    // следующий заход на него голос всё-таки подаст.
    this.audio.play().catch(() => {
      this.played = false;
      this._release();
    });

  }

  /**
   * Пропустить речь: звук обрывается, текст и рация уходят.
   *
   * От `mute` отличается тем, что не выключает вступление насовсем: это разовый
   * пропуск, а не галочка в панели.
   */
  skip() {
    if (!this.locked) return;

    this.played = true; // второй раз за сеанс оно не заведётся
    this.audio.pause();
    this.audio.currentTime = 0;
    this._release();
  }

  /**
   * Оборвать вступление: игрок ушёл с уровня, на котором оно звучит.
   *
   * Уйти можно и посреди речи — картой уровней, выходом с локации, стрелками в
   * панели разработчика, — а голос до этого продолжал говорить уже на другом
   * уровне: рация висела в углу, субтитры досказывали вводную, и персонаж стоял
   * замороженным посреди чужой локации, пока дорожка не кончится.
   *
   * От пропуска отличается тем, что речь не объявляется договорённой, и наружу
   * уходит другой сигнал: сноска о пропуске должна исчезнуть, а больше по концу
   * речи ничего и не ждёт. От `reset` — тем, что вступление остаётся
   * отзвучавшим: игрок слышал начало и сам решил уйти, и встречать его той же
   * речью при возвращении незачем.
   */
  stop() {
    if (!this.locked) return;

    this.played = true;
    this.audio.pause();
    this.audio.currentTime = 0;
    this._forgetWakeup();
    this._release(true);

    this.onStop?.();
  }

  /**
   * Выключить вступление совсем — или вернуть его.
   *
   * Выключенное не просто молчит: речь обрывается тут же, даже если голос уже
   * говорит, и вместе с ней уходят рация и субтитры. Разработчику, который
   * десятый раз перезапускает уровень, слушать эти полминуты незачем.
   *
   * @param {boolean} off
   */
  mute(off) {
    this.muted = off;
    if (!off) return;

    this.audio.pause();
    this.audio.currentTime = 0;
    this._release();
  }

  /**
   * Сыграть вступление снова: «С начала» начинает игру как в первый раз.
   *
   * Снимает и пометку «уже звучало», и все ожидания — и первого касания, и
   * пропуска — чтобы следующий заход на вводный уровень голос поднял заново.
   */
  reset() {
    this.audio.pause();
    this.audio.currentTime = 0;
    this.played = false;
    this.state = 'idle';
    this.text?.stop();

    clearTimeout(this._timer);
    this._timer = null;
    // Ожидание первого касания, если ворот не было, — тоже начисто.
    this._forgetWakeup();
  }

  /**
   * Забыть ожидание первого касания.
   *
   * Без этого речь, снятая до того, как её успели пустить, заводилась бы от
   * первого же тапа — и уже неизвестно где.
   */
  _forgetWakeup() {
    for (const event of ['pointerdown', 'touchstart', 'keydown']) {
      removeEventListener(event, this.start);
    }
  }

  /**
   * @param {boolean} [quiet] — не сообщать наружу, что речь кончилась: она не
   *   кончилась, а оборвана, и подсказке по управлению выходить не на что
   */
  _release(quiet = false) {
    // Речь и правда звучала — значит игрок уже в игре, и подсказке самое время.
    // Выключенное галочкой в панели вступление сюда не идёт: там ничего не
    // говорили, а подсказка выпрыгивала бы прямо на щелчок по галочке.
    const spoke = this.state === 'speaking';

    clearTimeout(this._timer);
    this._timer = null;

    this.text?.stop();
    this.state = 'done';

    // Речь отговорила — можно сказать игроку, как играть. Раньше этого мига
    // нельзя: подсказка легла бы поверх субтитров, и читать пришлось бы оба
    // текста разом.
    if (spoke && !quiet) this.onDone?.();
  }
}
