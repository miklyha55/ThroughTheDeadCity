/**
 * Откуда игра берёт свои файлы.
 *
 * Пути к ассетам не должны начинаться со слэша: он означает корень домена, и
 * стоит положить сборку в подпапку — модели, звук и локации перестают
 * находиться, а следом и сам код. Поэтому всё адресуется от того места, откуда
 * отдана страница: в разработке это корень, в сборке — та папка, где она лежит.
 */
const BASE = import.meta.env.BASE_URL;

/**
 * @param {string} path — путь без ведущего слэша, например `assets/audio/fire.mp3`
 * @returns {string} путь, пригодный и на dev-сервере, и в сборке в подпапке
 */
export function asset(path) {
  return `${BASE}${path}`;
}
