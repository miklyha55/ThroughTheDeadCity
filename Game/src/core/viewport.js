/**
 * Замок на масштаб и прокрутку страницы.
 *
 * Игра занимает весь экран и рисуется в холст, который подогнан под него ровно.
 * Стоит странице поехать — растянуться щипком, сдвинуться от оттяжки, — и холст
 * остаётся прежнего размера, а видно от него кусок: половина экрана показывает
 * игру, вторая половина то, что было под ней раньше. Со стороны это выглядит
 * сломанной игрой, хотя сломана всего лишь страница вокруг неё.
 *
 * Одной строкой в разметке этого не добиться. `user-scalable=no` телефоны
 * перестали слушать много лет назад — намеренно, чтобы нельзя было запретить
 * человеку приблизить мелкий текст. Для обычной страницы это правильно, для
 * полноэкранной игры без единой буквы — нет, и остаётся глушить сами жесты.
 *
 * Глушится ровно то, что ломает картинку:
 *
 *   - щипок двумя пальцами и его настольный двойник, колесо с Ctrl;
 *   - двойное касание, которым браузер приближает к абзацу;
 *   - прокрутка и оттяжка страницы, которой некуда ехать.
 *
 * Одиночные касания, стик и кнопки не трогаются вовсе: им эти события и не
 * нужны, а глушить всё подряд значило бы отобрать управление.
 */
export function lockViewport() {
  /**
   * Щипок в Safari. Нестандартные события, но только они и работают: на iOS
   * многопальцевый зум идёт мимо `touchmove` и отменить его иначе нельзя.
   */
  for (const event of ['gesturestart', 'gesturechange', 'gestureend']) {
    addEventListener(event, prevent, { passive: false });
  }

  // Щипок на трекпаде и Ctrl с колесом: настольный способ приблизить страницу.
  addEventListener('wheel', (e) => {
    if (e.ctrlKey) prevent(e);
  }, { passive: false });

  // Двумя пальцами по экрану — это всегда либо зум, либо прокрутка. Игре
  // хватает одного, и второй палец можно отбрасывать целиком.
  addEventListener('touchmove', (e) => {
    if (e.touches.length > 1) prevent(e);
  }, { passive: false });

  /**
   * Двойное касание: браузер приближает им текст.
   *
   * Ловится по времени между касаниями, а не событием `dblclick`: к тому мигу,
   * когда оно приходит, страница уже приблизилась. Порог четверть секунды —
   * столько браузер и ждёт второго касания.
   */
  let lastTap = 0;
  addEventListener('touchend', (e) => {
    const now = performance.now();
    if (now - lastTap < 260) prevent(e);
    lastTap = now;
  }, { passive: false });

  addEventListener('dblclick', prevent, { passive: false });

  // Прокрутка страницы, которой некуда ехать: оттяжка вниз, отскок вбок.
  // `scroll` отменить нельзя, поэтому просто возвращаем страницу на место.
  addEventListener('scroll', () => {
    if (scrollX !== 0 || scrollY !== 0) scrollTo(0, 0);
  }, { passive: true });

  // И то же самое для «видимой» части страницы: на телефоне она ездит отдельно
  // от самой страницы, когда всплывает клавиатура или тянут за край.
  const inner = window.visualViewport;
  if (inner) {
    const settle = () => {
      if (inner.offsetLeft !== 0 || inner.offsetTop !== 0) scrollTo(0, 0);
    };
    inner.addEventListener('scroll', settle);
    inner.addEventListener('resize', settle);
  }
}

function prevent(event) {
  if (event.cancelable) event.preventDefault();
}
