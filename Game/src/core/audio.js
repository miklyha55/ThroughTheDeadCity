import * as THREE from 'three';

/**
 * Единый слушатель, через который идёт весь звук игры.
 *
 * Это штатный `THREE.AudioListener`: он держит общий `AudioContext`, и его же
 * берут `THREE.AudioLoader` при разборе файлов и `THREE.Audio` при создании
 * голоса. Поэтому короткие звуки, музыка и вступление оказываются в одном графе
 * с одним выходом — а не тремя независимыми, как было раньше.
 *
 * Один граф важен не ради красоты. Браузер разрешает звук не вообще, а
 * конкретному контексту, и пока контекстов несколько, разрешение приходится
 * выпрашивать для каждого отдельно. Один контекст будится один раз.
 */
export const listener = new THREE.AudioListener();

/**
 * Повесить слушателя на камеру — как предписано документацией three.
 *
 * Для непозиционного `THREE.Audio` положение слушателя ни на что не влияет:
 * панорамы у него нет. Но `THREE.PositionalAudio`, если он когда-нибудь
 * понадобится, считает громкость именно от слушателя, и тогда он уже должен
 * ехать вместе с камерой.
 *
 * @param {THREE.Camera} camera
 */
export function attachListener(camera) {
  camera.add(listener);
}

/**
 * Готов ли звук звучать прямо сейчас.
 *
 * Спрашивать обязательно перед каждым запуском. Пока контекст спит, его часы
 * стоят на нуле, и запущенный в это время голос планируется на нулевую отметку.
 * При пробуждении часы прыгают сразу на реальное прошедшее время, эта отметка
 * оказывается далеко в прошлом — и браузер выбрасывает такой голос целиком.
 * Звук не откладывается, он теряется навсегда: ровно отсюда бралась тишина в
 * первые секунды игры на телефоне.
 */
export function audioReady() {
  return listener.context.state === 'running';
}

const EVENTS = ['pointerdown', 'touchstart', 'keydown'];

let greeted = false;

/**
 * Нажимал ли игрок хоть раз — то есть получено ли разрешение на звук.
 *
 * Отличается от `audioReady` тем, что отвечает сразу. Пробуждение контекста
 * асинхронное: между нажатием и словом «работаю» проходит какое-то время, на
 * телефоне заметное. Тому, кто решает «ждать ли ещё одного касания», важно
 * именно нажатие, а не готовность железа, иначе музыка и вступление молча
 * ждали бы второго тапа после того, как игрок уже нажал «Играть».
 */
export function audioGreeted() {
  return greeted;
}

/**
 * Разбудить звук. Зовётся из обработчика касания — и только оттуда.
 *
 * Делает две вещи, и обе обязательны. `resume()` снимает запрет, наложенный
 * браузером до первого действия игрока. Пустой односэмпловый кусок, запущенный
 * тут же, поднимает звуковую сессию на iOS: там одного `resume()` не хватает,
 * контекст отвечает «работаю», а наружу ничего не идёт, пока в нём хоть раз
 * не проиграли настоящий источник.
 *
 * Обе операции синхронные, внутри самого жеста: отложенные на следующий кадр
 * или на `await` браузер уже не считает ответом на действие игрока.
 */
export function wakeAudio() {
  greeted = true;

  const ctx = listener.context;
  if (ctx.state === 'running') return;

  try {
    const knock = ctx.createBufferSource();
    knock.buffer = ctx.createBuffer(1, 1, ctx.sampleRate);
    knock.connect(ctx.destination);
    knock.start(0);
  } catch {
    // контекст не дал создать источник — обойдёмся одним resume
  }

  ctx.resume().then(_settle, () => {});
}

/** Слушатели снимаются только когда звук действительно пошёл. */
function _settle() {
  if (listener.context.state !== 'running') return;
  for (const event of EVENTS) removeEventListener(event, wakeAudio);
}

/**
 * Ждать первого действия игрока и разбудить звук.
 *
 * Подписка держится до тех пор, пока контекст не заработает, а не снимается
 * после первой попытки. Одной попытки мало: браузер может отказать — вкладка
 * не в фокусе, жест пришёлся на чужой обработчик, — и тогда без второго захода
 * игра осталась бы немой до конца сеанса. Музыка так и умела переспросить, а
 * короткие звуки нет, отсюда и выходило, что музыка играет, а выстрелов не
 * слышно.
 */
export function unlockAudio() {
  for (const event of EVENTS) addEventListener(event, wakeAudio);
  _settle();
}
