/**
 * Мерки по земле.
 *
 * Игра идёт на плоскости: высота есть у прыжка, у летящего ящика и у брызг, но
 * всё, что решает «далеко или близко» — радиус огня, дистанция подбора, радиус
 * удара, — считается без неё. Иначе зомби на дорожной плите оказывался бы чуть
 * дальше того же зомби на земле.
 */

/**
 * Расстояние между двумя точками по земле.
 * @param {{x: number, z: number}} a @param {{x: number, z: number}} b
 */
export function flatDistance(a, b) {
  return Math.hypot(a.x - b.x, a.z - b.z);
}
