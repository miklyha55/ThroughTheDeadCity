import * as THREE from 'three';
import { CONFIG } from '../config.js';
import { listener, resumeAudio, audioGreeted } from './audio.js';

const CFG = CONFIG.music;

/**
 * Фоновая музыка: своя дорожка на каждый уровень, по кругу до его конца.
 *
 * Идёт через тот же `THREE.Audio` и того же слушателя, что и всё остальное, но
 * источником взят не разобранный кусок, а потоковый элемент —
 * `setMediaElementSource`. Так предписано и документацией three, и здравым
 * смыслом: дорожка уровня это несколько минут, а разобранная в память минута
 * стоит около пятнадцати мегабайт. Три дорожки съели бы больше, чем вся
 * остальная игра, ради звука, который и так прекрасно течёт с диска.
 *
 * Дорожка выбирается номером уровня — файл `1.mp3` лежит под первым, `2.mp3` под
 * вторым. Пока номер не сменился, музыка не перезапускается: возврат на ту же
 * локацию не обрывает её с начала.
 *
 * Первый запуск ждёт действия игрока — раньше и нельзя: браузер не даёт начать
 * звук, пока ничего не нажато, и молча отклоняет попытку. Обычно это нажатие на
 * воротах, ещё до загрузки; если ворот почему-то не было, годится любое первое
 * касание, мышь или клавиша.
 *
 * Пока вкладка скрыта, музыка замолкает: играть в пустоту незачем, а вернувшись,
 * игрок продолжит с того же места.
 *
 * Поверх дорожки идёт ветер — одна зацикленная запись своим потоком. Он не про
 * уровень, а про мир, поэтому со сменой локации не перезапускается и `silence`
 * его не снимает: под ответной передачей молчит музыка, а город — нет.
 */
export class Music {
  constructor() {
    this.audio = new Audio();
    this.audio.loop = true;
    this.audio.preload = 'auto';

    // Громкость крутится на стороне three, а не элемента: одна ручка на весь
    // граф. Элемент остаётся на единице, иначе они умножались бы друг на друга.
    this.sound = new THREE.Audio(listener);
    this.sound.setMediaElementSource(this.audio);
    this.sound.setVolume(CFG.volume);

    // Ветер: второй поток, идущий параллельно любой дорожке. Своим элементом, а
    // не разобранным куском, по той же причине, что и музыка, — это минуты
    // звука, и держать их в памяти незачем.
    this.wind = new Audio();
    this.wind.loop = true;
    this.wind.preload = 'auto';
    this.wind.src = CFG.wind;

    this.windSound = new THREE.Audio(listener);
    this.windSound.setMediaElementSource(this.wind);
    this.windSound.setVolume(CFG.windVolume);

    this.track = null; // номер уровня, чья дорожка сейчас заряжена
    // Разрешение мог дать уже экран с кнопкой «Играть» — тогда ждать нечего и
    // музыка пойдёт сразу, как только у уровня появится номер.
    this.allowed = audioGreeted();
    this.start = this.start.bind(this);

    // Слушаем и касание, и мышь, и клавиши: на десктопе экрана касаться нечем.
    for (const event of ['pointerdown', 'touchstart', 'keydown']) {
      addEventListener(event, this.start, { once: true });
    }

    document.addEventListener('visibilitychange', () => {
      if (!this.allowed) return;
      if (document.hidden) this.hush(); else this.unhush();
    });

    // Разрешение мог дать ещё экран с кнопкой «Играть» — тогда ветру нечего
    // ждать: дорожки у него нет, и повода начаться он иначе не дождётся вовсе.
    this._blow();
  }

  /**
   * Поставить дорожку уровня. Та же самая играет дальше без перерыва.
   * @param {number} track — номер уровня
   */
  play(track) {
    if (track === this.track) return;

    // Уровень без дорожки: на шоссе её нет вовсе, и это нарочно. Ставить
    // несуществующий файл нельзя — браузер отклонит воспроизведение, а по
    // отказу мы снимаем разрешение на звук и вместе с музыкой замолкает ветер.
    if (track === null || track === undefined) {
      this.silence();
      return;
    }

    this.track = track;
    this.audio.src = `${CFG.folder}${track}.mp3`;

    // Своя громкость, если у уровня она задана: на вводной поверх музыки идёт
    // голос по рации, и общая её заглушала.
    this.sound.setVolume(CFG.byLevel?.[track] ?? CFG.volume);

    this._resume();
  }

  /**
   * Замолчать совсем: дорожка снимается, и следующая начнётся с начала.
   *
   * Нужно там, где музыка мешает: под ответной передачей звучит только голос, и
   * играть под ним нечему.
   */
  silence() {
    this.track = null;
    this.audio.pause();
    this.audio.currentTime = 0;
  }

  /**
   * Замолчать на время, не теряя места.
   *
   * От `silence` отличается тем, что дорожка остаётся заряженной и стоит там,
   * где её застали: вернувшись, игрок услышит ровно то место, на котором ушёл,
   * а не начало трека заново.
   *
   * Поводов два, и оба чужие: вкладку убрали из виду и площадка показывает
   * рекламу. Под роликом игра обязана молчать — играющая поверх него музыка
   * это уже вопрос к модерации, а не к вкусу.
   *
   * Ветер уходит вместе с музыкой, в отличие от `silence`: там молчит дорожка,
   * а город живёт, здесь же не звучит вообще ничего.
   */
  hush() {
    this.audio.pause();
    this.wind.pause();
  }

  /** Заговорить снова — с того же места, на котором замолчали. */
  unhush() {
    this._resume();
    this._blow();
  }

  /**
   * Пустить ветер. Зовётся отовсюду, где мог появиться звук: он идёт всегда,
   * и своего повода начинаться у него нет — в отличие от дорожки, которая ждёт
   * номера уровня.
   */
  _blow() {
    if (!this.allowed) return;

    resumeAudio();
    this.wind.play().catch(() => {}); // не пустили — пойдёт со следующей попытки
  }

  /** Пустить музыку, когда игрок впервые тронул экран. */
  start() {
    if (this.allowed) return;
    this.allowed = true;
    this._resume();
    this._blow();
  }

  _resume() {
    // Дорожки нет, только если её и не ставили. Сравниваем именно с пустотой:
    // у вводной локации номер ноль, а он считается ложью — и её музыка молчала,
    // хотя файл лежал на месте.
    if (!this.allowed || this.track === null || this.track === undefined) return;

    // Элемент теперь звучит не сам по себе, а через общий граф: пока контекст
    // спит, играющая дорожка не даёт ни звука. Поэтому поднимаем его здесь же —
    // из касания это сработает сразу, а из смены уровня хотя бы попробует.
    //
    // Именно поднимаем, а не «здороваемся»: сюда приходят и без всякого жеста —
    // на смене уровня и на возврате во вкладку, — и объявлять после этого, что
    // игрок нажал, было бы неправдой.
    resumeAudio();
    this._blow(); // ветер идёт вместе с любой дорожкой, с первой же и до конца

    this.audio.play().catch(() => {
      // Браузер не пустил — ждём следующего касания и пробуем снова.
      this.allowed = false;
      addEventListener('pointerdown', this.start, { once: true });
    });
  }
}
