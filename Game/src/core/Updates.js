import { CONFIG } from '../config.js';

const CFG = CONFIG.updates;

/**
 * Узнаёт, что на сервере лежит уже не та игра, которая открыта.
 *
 * Сборка кладёт рядом с игрой файл с отпечатком всех своих файлов. Страница
 * читает его на старте, запоминает — и дальше лишь сверяется. Разошлось значит
 * вышла новая сборка.
 *
 * Свой отпечаток игра знает: он считается по исходникам ещё до сборки и
 * вписывается внутрь кода при ней же. Поэтому сверяется именно «что я такое» с
 * «что лежит на сервере».
 *
 * Раньше сверялось иначе — с тем, что лежало на сервере в миг открытия. Так
 * нельзя, и это давало две дыры разом. Открыв игру уже ПОСЛЕ выкладки, игрок не
 * видел кнопки никогда: расходиться было нечему, обе величины брались с одного
 * и того же сервера. А если сама страница пришла из кэша — то есть игрок и
 * правда сидел на старой версии, — в память ложился уже новый отпечаток, и
 * старая версия считала себя свежей.
 *
 * Читается всегда мимо кэша. Иначе браузер отдаст тот же файл, что и час назад,
 * и новая сборка так и останется незамеченной.
 *
 * Игру никто не перезагружает сам. Посреди боя это было бы хуже устаревшей
 * версии: прогресс уровня потерян, и непонятно за что. Сказать игроку и дать
 * кнопку — его дело, когда нажать.
 */
export class Updates {
  /** @param {() => void} onFound — зовётся один раз, когда отпечаток разошёлся */
  constructor(onFound) {
    this.onFound = onFound;
    this.known = null;   // что лежало на сервере, когда игра открылась
    this.found = false;  // расхождение уже нашли и сказали
    this._timer = null;
    this._check = this._check.bind(this);

    // Что происходило: последние события и ответы. На телефоне консоли нет, и
    // без этого списка проверять слежение можно только вслепую.
    this.log = [];
  }

  /** Записать, что случилось. Хранится только хвост: больше и не нужно. */
  _note(text) {
    const t = new Date().toTimeString().slice(0, 8);
    this.log.push(`${t} ${text}`);
    if (this.log.length > 12) this.log.shift();
    this.onNote?.(this.log);
  }

  /**
   * Запомнить нынешний отпечаток и начать сверяться.
   *
   * Точку отсчёта берём с первого удачного ответа, а не с первой попытки. На
   * телефоне первая попытка приходится на самую загрузку — сеть занята
   * мегабайтами моделей, и ответа можно не дождаться. Раньше на этом всё и
   * заканчивалось: отпечатка нет, слежение молча не заводится, кнопка не
   * появится уже никогда.
   */
  async start() {
    // Свой отпечаток известен сразу, ждать сервера для этого не нужно.
    this.known = typeof __BUILD__ === 'string' ? __BUILD__ : null;

    if (!this.known) {
      // Отпечатка в коде нет — старая сборка или запуск в обход сборщика.
      // Тогда работаем по-прежнему: запоминаем, что лежало при открытии.
      for (let попытка = 0; попытка < CFG.tries; попытка++) {
        this.known = await this._read();
        if (this.known) break;
        this._note(`попытка ${попытка + 1}: не прочитал`);
        await new Promise((r) => setTimeout(r, CFG.retryAfter * 1000));
      }
      if (!this.known) {
        this._note('отпечаток не прочитан, слежения нет');
        return; // сервер файла не отдаёт вовсе — живём без обновлений
      }
    }
    this._note(`я версия ${this.known}`);

    // Сверяемся сразу, а не через минуту: игрок мог открыть игру из кэша, и
    // тогда она устарела уже в этот самый миг.
    await this._check('на старте');

    this._timer = setInterval(this._check, CFG.interval * 1000);

    /**
     * Проверка при каждом возвращении к игре.
     *
     * На телефоне это главный путь, а вовсе не таймер: стоит свернуть игру или
     * погасить экран, как браузер замораживает таймеры вкладки, и следующий
     * круг опроса случится неизвестно когда. А обновление выходит как раз
     * тогда, когда игру отложили.
     *
     * Событий три, потому что ни одному нельзя доверить это в одиночку.
     * `visibilitychange` на телефонах приходит не всегда; `pageshow` ловит
     * возврат кнопкой «назад», когда страницу достают из кэша целиком, живой и
     * не перезагруженной; `focus` остаётся на случай, когда не пришло ни то ни
     * другое.
     */
    document.addEventListener('visibilitychange', () => {
      if (!document.hidden) this._check('вернулись на вкладку');
    });
    addEventListener('pageshow', () => this._check('страница показана'));
    addEventListener('focus', () => this._check('фокус'));
  }

  async _check(повод = 'по таймеру') {
    if (this.found) return;

    const свежий = await this._read();
    if (!свежий) {
      this._note(`${повод}: сервер не ответил`);
      return;
    }
    if (свежий === this.known) {
      this._note(`${повод}: та же версия`);
      return;
    }

    this._note(`${повод}: НОВАЯ ВЕРСИЯ ${свежий}`);
    this.found = true;
    clearInterval(this._timer);
    this._timer = null;
    this.onFound?.();
  }

  async _read() {
    try {
      // Метка времени в адресе плюс запрет кэша: два способа на случай, если
      // между игрой и сервером стоит прокси, который слушается только одного.
      const res = await fetch(`${CFG.file}?t=${Date.now()}`, { cache: 'no-store' });
      if (!res.ok) return null;

      const data = await res.json();
      return typeof data?.build === 'string' ? data.build : null;
    } catch {
      return null; // сети нет или файл битый: это не повод ломать игру
    }
  }

  /**
   * Перейти на новую сборку.
   *
   * Имена файлов кода сборщик меняет при каждой правке, поэтому обычной
   * перезагрузки достаточно: страница перечитается, а за ней подтянется и всё
   * новое. Хранилища ответов чистим на всякий случай — если игру когда-нибудь
   * завернут в офлайн-оболочку, без этого она так и осталась бы на старом.
   */
  static async apply() {
    try {
      if (window.caches) {
        const ключи = await caches.keys();
        await Promise.all(ключи.map((k) => caches.delete(k)));
      }
    } catch {
      // не дали почистить — перезагрузка всё равно нужна
    }

    location.reload();
  }
}
