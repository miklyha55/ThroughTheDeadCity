/**
 * Счёт пути: сколько зомби уложено, сколько раз погиб герой и сколько он идёт.
 *
 * Нужен одному финалу — показать игроку, чем кончился его поход. Поэтому живёт
 * в памяти и никуда не сохраняется: это итог одного прохождения, а не рекорд.
 *
 * Время считается от первого шага на первом уровне и до выхода из города, с
 * поправкой на паузы: под заставкой, картой уровней и рекламой герой не идёт, и
 * это время в путь не засчитывается.
 *
 * Считается весь поход, а не последний заход в игру: город проходят в несколько
 * присестов, и время закрытой вкладки вместе с ней не пропадает. Копится оно у
 * площадки, рядом с прогрессом, а сюда приходит при запуске `seed` и уходит
 * обратно через `onSpent` — счёту всё равно, кто там его хранит.
 */
class Tally {
  constructor() {
    this.kills = 0;
    this.deaths = 0;
    this._since = 0;   // когда пошёл нынешний отрезок пути, мс; ноль — стоим
    this._walked = 0;  // и сколько уже насчитано, мс
    this._sent = 0;    // и сколько из насчитанного уже ушло в сохранения
    this.onSpent = null; // кому отдавать накопленное; ставится снаружи
  }

  /**
   * Взять время прошлых заходов: игрок продолжает начатый поход.
   *
   * Зовётся один раз при запуске, до первого шага. Отданным считается сразу всё
   * пришедшее: оно уже лежит в сохранениях, и возвращать его туда незачем.
   *
   * @param {number} seconds — сколько уже пройдено
   */
  seed(seconds) {
    this._walked = Math.max(0, Number(seconds) || 0) * 1000;
    this._sent = this._walked;
  }

  /** Начать заново: игра пошла с первого уровня. */
  reset() {
    this.kills = 0;
    this.deaths = 0;
    this._since = 0;
    this._walked = 0;
    this._sent = 0;
  }

  /** Часы идут: игрок в игре. */
  resume() {
    if (!this._since) this._since = performance.now();
  }

  /** И стоят: заставка, карта уровней, реклама, финал. */
  pause() {
    if (!this._since) return;

    this._walked += performance.now() - this._since;
    this._since = 0;
    this._spend();
  }

  /**
   * Отдать наружу то, что насчиталось с прошлого раза.
   *
   * Отдаётся приростом, а не всей суммой: за сохранения отвечает не счёт, и
   * складывать их дело того, кто хранит. Зовётся на каждой паузе — то есть на
   * смене уровня, экране смерти и под картой, — и этого хватает: игра нигде не
   * идёт дольше одного уровня без остановки.
   */
  _spend() {
    const fresh = this._walked - this._sent;
    if (fresh <= 0) return;

    this._sent = this._walked;
    this.onSpent?.(fresh / 1000);
  }

  /** Сколько всего пройдено, с. */
  get seconds() {
    const running = this._since ? performance.now() - this._since : 0;
    return (this._walked + running) / 1000;
  }

  /** Время в виде «7:42» — минуты и секунды. */
  get clock() {
    const total = Math.max(0, Math.round(this.seconds));
    const minutes = Math.floor(total / 60);
    return `${minutes}:${String(total % 60).padStart(2, '0')}`;
  }
}

export const tally = new Tally();
