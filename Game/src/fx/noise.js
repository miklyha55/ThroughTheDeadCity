/**
 * Шум для шейдеров — один на всю игру.
 *
 * По нему рисуется и позёмка на локации, и песок на финальном экране. Держать
 * его в двух местах значило бы получить два разных песка: подкрутил рисунок в
 * одном — и картинки разъехались.
 *
 * Текстура для этого не нужна: значение в узлах решётки берётся из хеша, между
 * узлами — сглаженная интерполяция, а несколько частот друг поверх друга дают
 * рваные края вместо мягких клякс.
 */
export const NOISE_GLSL = /* glsl */`
  float hash(vec2 p) {
    return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453);
  }

  float noise(vec2 p) {
    vec2 cell = floor(p);
    vec2 part = fract(p);
    vec2 smoothed = part * part * (3.0 - 2.0 * part);

    return mix(
      mix(hash(cell), hash(cell + vec2(1.0, 0.0)), smoothed.x),
      mix(hash(cell + vec2(0.0, 1.0)), hash(cell + vec2(1.0, 1.0)), smoothed.x),
      smoothed.y
    );
  }

  // Крупные пятна задают общий рисунок, мелкие рвут их края.
  float layered(vec2 p) {
    return noise(p) * 0.55 + noise(p * 2.3) * 0.28 + noise(p * 4.7) * 0.17;
  }
`;
