import { CONFIG } from '../config.js';
import { regainFocus } from '../core/yandex.js';

/**
 * Выбор кнопки с клавиатуры: стрелки водят выбор, Enter жмёт выбранную.
 *
 * Заведено общим, а не в каждом экране по-своему, ровно потому, что экранов с
 * двумя кнопками в игре несколько — смерть, вопрос «точно?», финал, — и
 * разойдись они в мелочах, игрок за столом заново учил бы клавиши на каждом.
 *
 * Выбор ведётся своим полем, а не фокусом браузера. Причин две. Кнопка под
 * фокусом отвечает на Enter сама, помимо нас, и таким путём мимо `click()`
 * прошло бы всё, что на нём висит, — заслонки, запрет второго нажатия. И
 * обводку фокуса игра снимает у всех кнопок разом, так что видно её всё равно
 * не было бы.
 *
 * Метку ставит сам класс — `is-picked` на выбранной кнопке. Только за столом:
 * на телефоне выбирать нечем, а подсвеченная кнопка читалась бы как нажатая.
 * При этом `picked` заполняется всегда, и Enter с подключённой клавиатуры
 * сработает даже там, где метки не видно.
 *
 * Подсказку про клавиши он рисует тоже сам и отдаёт её готовой строкой —
 * `choice.hint`, — а экран только ставит её в нужное место своей карточки.
 * Иначе каждый экран писал бы её по-своему, и это уже случалось: про Enter
 * говорил один экран смерти, а финал и вопрос «точно?» молчали, хотя клавиши
 * там работают так же. Заодно и текст выбирается по делу: пока кнопка одна,
 * обещать стрелки незачем.
 */
export class Choice {
  /**
   * @param {HTMLElement[]} buttons — кнопки по порядку, как стоят на экране
   * @param {() => boolean} active — отвечает ли этот экран на клавиши прямо
   *   сейчас. Спрашивается на каждое нажатие: экраны наслаиваются — вопрос
   *   «точно?» встаёт поверх экрана смерти, — и отвечать должен верхний.
   * @param {boolean} [row] — кнопки стоят в ряд, а не столбиком. На саму работу
   *   не влияет: водят обе оси всегда. Влияет только на подсказку — обещать
   *   надо те стрелки, к которым игрок и потянется, глядя на эти кнопки.
   */
  constructor(buttons, active, row = false) {
    this.buttons = buttons;
    this.active = active;
    this.row = row;
    this.picked = null;
    this.keyboard = false;

    // Строка подсказки. Заводится всегда, даже там, где её не покажут: экран
    // ставит её в разметку один раз, при сборке, а видимость решается уже на
    // каждом показе — клавиатуру могут и подключить.
    this.hint = document.createElement('p');
    this.hint.className = 'keyhint';
    this.hint.hidden = true;

    addEventListener('keydown', (event) => this._key(event));
  }

  /**
   * Выбор на первую доступную кнопку. Зовётся при каждом показе экрана.
   *
   * Всегда на первую, а не на ту, что осталась с прошлого раза: первой везде
   * стоит безопасный и самый частый ответ, а доставшийся по наследству выбор
   * на «Начать сначала» был бы западнёй.
   */
  reset() {
    /**
     * Забрать клавиатуру обратно.
     *
     * Экран, который сейчас откроется, обещает игроку клавиши — и обещание надо
     * сдержать. На площадке игра живёт в чужом окне, и её собственные окна —
     * ролик, оценка, выбор аккаунта — уводят фокус, после чего ни одно нажатие
     * до игры не доходит. Тут и выходило хуже всего: подсказка обещает стрелки и
     * Enter, а они молчат.
     */
    regainFocus();

    // Пересчитываем здесь, а не в конструкторе: к первому показу экрана
    // клавиатуру могли и подключить.
    this.keyboard = matchMedia('(hover: hover) and (pointer: fine)').matches;
    this._put(this._alive()[0] ?? null);
    this.refresh();
  }

  /**
   * Пересчитать подсказку, не трогая выбор.
   *
   * Набор кнопок меняется и на уже открытом экране: «Оценить» на финале ждёт
   * ответа площадки и появляется через мгновение после самого экрана. Без
   * пересчёта подсказка осталась бы от той поры, когда кнопка была одна, и
   * молчала бы про стрелки.
   *
   * Выбор при этом остаётся там, где стоял: игрок мог успеть его увести, и
   * дёргать его из-под руки нельзя. Переносим только если выбранная кнопка
   * как раз и пропала — иначе Enter жал бы спрятанное.
   */
  refresh() {
    const alive = this._alive();

    // Про стрелки говорим, только когда им есть куда вести: обещать выбор там,
    // где кнопка одна, — враньё.
    const many = this.row ? CONFIG.keys.pickRow : CONFIG.keys.pick;
    this.hint.textContent = alive.length > 1 ? many : CONFIG.keys.press;
    this.hint.hidden = !this.keyboard || !alive.length;

    if (this.picked && !alive.includes(this.picked)) this._put(alive[0] ?? null);
  }

  /** Снять выбор и метку: экран ушёл. */
  clear() {
    this._put(null);
  }

  /** Кнопки, которые сейчас и правда можно нажать. */
  _alive() {
    return this.buttons.filter((button) => !button.hidden && !button.disabled);
  }

  _put(button) {
    this.picked = button;
    for (const one of this.buttons) {
      one.classList.toggle('is-picked', this.keyboard && one === button);
    }
  }

  /**
   * Сдвинуть выбор на шаг. Список не закольцован: с краёв выбор упирается.
   *
   * Закольцевать было заманчиво, но здесь это ловушка: на краю всегда стоит
   * то, после чего ничего не вернуть, и лишнее нажатие не должно перекидывать
   * выбор на него с другого конца списка.
   */
  _move(step) {
    const alive = this._alive();
    if (!alive.length) return;

    const at = alive.indexOf(this.picked);
    const next = at < 0 ? 0 : at + step;
    this._put(alive[Math.min(alive.length - 1, Math.max(0, next))]);
  }

  _key(event) {
    if (event.repeat || !this.active()) return;

    if (event.code === 'Enter' || event.code === 'NumpadEnter') {
      // Если выбора почему-то нет — жмём первую доступную: Enter за столом
      // обязан что-то делать, молчащая клавиша читается как поломка.
      const button = this.picked ?? this._alive()[0];
      if (!button) return;

      event.preventDefault();
      button.click();
      return;
    }

    const step = ARROWS[event.code];
    if (!step) return;

    // Страница прибита к экрану, но стрелки на ней всё равно листают фокус и
    // прокрутку — под открытым окном они заняты.
    event.preventDefault();
    this._move(step);
  }
}

/**
 * Куда ведёт каждая стрелка по списку: назад или вперёд.
 *
 * Обе оси делают одно и то же, хотя на одних экранах кнопки стоят столбиком, а
 * на других в ряд. Рука тянется к стрелкам не глядя, и наказывать за промах по
 * оси незачем — тем более что на разных экранах «правильная» ось разная.
 */
const ARROWS = {
  ArrowUp: -1,
  ArrowLeft: -1,
  ArrowDown: 1,
  ArrowRight: 1,
};
