import { CONFIG } from '../config.js';
import { levelName } from '../core/i18n.js';
import { asset } from '../core/paths.js';

const CFG = CONFIG.splash;

/**
 * Заставка между уровнями: картинка на весь экран и полоса загрузки по центру.
 *
 * Загрузка локации сама по себе быстрая и рывками: сборка геометрии идёт одним
 * куском и никаких долей не сообщает. Поэтому полоса не притворяется точной —
 * она движется сама, равномерно, а по готовности доводится до конца. Так игрок
 * видит, что игра занята делом, и не смотрит в застывший экран.
 *
 * Заставка держится на экране не меньше `minTime`: без этого на быстрой машине
 * она мелькала бы вспышкой, что хуже, чем секунда ожидания.
 */
export class Splash {
  /** @param {import('./LoadBar.js').LoadBar} bar — полоса общая с экраном загрузки */
  constructor(bar, container = document.body) {
    this.bar = bar;
    this.root = document.createElement('div');
    this.root.className = 'splash';
    this.root.hidden = true;

    /**
     * Чёрная вуаль под заставкой.
     *
     * Заставка уходит одним кадром — и без вуали на её месте сразу возникал
     * готовый уровень: резкая подмена картинки читалась как сбой. Теперь под
     * заставкой чёрное, и когда она уходит, чернота растворяется, открывая
     * уровень из темноты. Висит поверх игры и её кнопок, но ниже заставки.
     */
    this.veil = document.createElement('div');
    this.veil.className = 'veil veil--black';
    container.appendChild(this.veil);

    /**
     * Слой картинки — свой у каждого уровня, и все они стоят в разметке сразу.
     *
     * Раньше слой был один, и на каждом переходе ему меняли картинку. Сколько
     * это ни ускоряй — заранее скачай, заранее распакуй, — остаётся работа,
     * которая приходится ровно на миг перехода: браузер впервые рисует новый
     * фон, растягивает его под экран и подменяет прежний. Оттуда и дёрганье, и
     * мелькание пройденного уровня.
     *
     * Теперь на переходе не происходит ничего, кроме смены класса. Слои заведены
     * на старте, картинки в них проставлены тогда же, и все они отрисовываются
     * за первый же показ заставки — тот, что идёт под общим экраном загрузки.
     * Невидимые держатся нулевой прозрачностью, а не снятием с показа: снятого
     * браузер не рисует, и вся подготовка пропала бы впустую.
     */
    this.layers = new Map(); // номер уровня → его слой
    this.image = null;       // какой показан сейчас

    this.caption = document.createElement('div');
    this.caption.className = 'splash__caption';

    this.root.append(this.caption);
    container.appendChild(this.root);

    this.progress = 0;
    this.shownAt = 0;
    this._timer = null;
    // Метка кэша: появляется только после пересборки ресурсов. По умолчанию её
    // нет намеренно — адрес должен совпадать с тем, по которому картинку грел
    // загрузчик, иначе браузер считает их разными файлами и качает второй раз
    // уже во время показа. Ровно так заставка и выходила пустой.
    this.stamp = 0;
    this.levels = new Map(); // id уровня → чем его встречать; заполняется на старте
  }

  /**
   * Завести слой под картинку уровня. Один раз на номер.
   *
   * Номер, а не id: картинка лежит под номером, и у двух уровней он может
   * совпасть — например у запасного, которым встречают неизвестный.
   */
  _layer(number) {
    let layer = this.layers.get(number);
    if (layer) return layer;

    layer = document.createElement('div');
    layer.className = 'splash__image';

    const bust = this.stamp ? `?v=${this.stamp}` : '';
    layer.style.backgroundImage = `url(${CFG.folder}${number}.png${bust})`;

    // Перед подписью: она должна лежать поверх картинки, а не под ней.
    this.root.insertBefore(layer, this.caption);
    this.layers.set(number, layer);
    return layer;
  }

  /**
   * Показать заставку и вести полосу, пока идёт работа.
   *
   * Уже показанную не перезапускаем: загрузка игры и загрузка первого уровня
   * идут подряд, и полоса, отмотанная на ноль посередине, читалась бы как сбой.
   *
   * Картинку прежнего уровня не гасим. Новую поставят, как только прочитают его
   * файл, а до тех пор пусть висит старая — пустое место здесь означает чёрный
   * экран, и он тем заметнее, чем дольше грузится.
   */
  /**
   * @param {boolean} [covered] — поднимается под другим экраном. Такая заставка
   *   полосу не ведёт: полоса общая, и пока сверху экран загрузки, она его.
   */
  show(covered = false) {
    // Каждый показ свой: по нему уход и узнаёт, его ли ещё очередь.
    this.turn = (this.turn ?? 0) + 1;

    if (!this.root.hidden) return; // уже идёт

    this.progress = 0;
    this.shownAt = performance.now();

    this.covered = covered;
    this.veil.classList.add('veil--black'); // под заставкой — сразу чёрное, без перехода
    this.root.hidden = false;
    if (!covered) this.bar.show(0);

    // Полоса ползёт сама и тормозит у конца: дойти до края раньше, чем работа
    // закончилась, ей нельзя — иначе она застынет полной и будет врать.
    clearInterval(this._timer);
    this._timer = setInterval(() => {
      this.progress += (CFG.ceiling - this.progress) * CFG.ease;
      if (!this.covered) this.bar.set(this.progress);
    }, CFG.tick);
  }

  /**
   * Чей уровень грузится. Известно только после чтения его файла, поэтому и
   * название, и картинка ставятся здесь, а не при показе.
   *
   * @param {string} title — название уровня
   * @param {number} number — его номер: под ним лежит и картинка, и музыка
   */
  /**
   * Чей уровень грузится: подпись и картинка.
   *
   * Обе смены мгновенные и без единой строчки работы с картинками: слой под
   * этот уровень заведён ещё на старте, и всё, что здесь происходит, — снятие
   * класса с прежнего и постановка на нужный.
   *
   * @param {string} title — название уровня
   * @param {number} number — его номер: под ним лежит и картинка, и музыка
   */
  setLevel(title, number) {
    this.caption.textContent = title ?? '';

    const layer = this._layer(number);
    if (layer === this.image) return;

    this.image?.classList.remove('splash__image--on');
    layer.classList.add('splash__image--on');
    this.image = layer;
  }

  /**
   * Запомнить цепочку уровней: чем встречать каждый.
   *
   * Читается один раз на старте, вместе со всем остальным. Дальше заставка знает
   * ответ сразу и ставит нужную картинку ещё до показа — иначе на экране сперва
   * мелькает предыдущий уровень, пока читается файл следующего.
   *
   * @param {Array<{id: string, number: number, name: string}>} levels
   */
  learn(levels) {
    for (const level of levels) {
      this.levels.set(level.id, level);
      this._layer(level.number); // слой заводится сразу, вместе со знанием об уровне
    }
    this._layer(CFG.bootLevel); // и запасной, которым встречают незнакомый
  }

  /**
   * Закрыть экран чернотой прямо сейчас.
   *
   * Между тем, как уходит один экран, и тем, как встаёт заставка, бывает
   * промежуток: экран итога тает почти секунду, перед следующим уровнем может
   * встать рекламный ролик, а сама загрузка начинается только после них. Всё
   * это время под уходящим экраном видна живая игра — персонаж, зомби,
   * недостроенный уровень, — и на глазах у игрока это читается как скачок.
   *
   * Вуаль лежит ниже всех экранов и выше игры: она закрывает именно её, не
   * мешая тому, что ещё тает сверху. Снимет её сама заставка, когда уйдёт.
   *
   * Звать можно сколько угодно раз: повторный вызов ничего не меняет.
   */
  cover() {
    this.veil.classList.add('veil--black');
  }

  /**
   * Приготовиться встречать уровень: поставить его название и картинку.
   *
   * Зовётся до показа. Если уровень знаком по цепочке — всё ставится тут же, без
   * единого запроса. Незнакомый (открытый через `?location=`) дочитывается из
   * файла, а до тех пор висит запасная картинка: пустое место читается как сбой.
   *
   * @param {string} id — какой уровень сейчас откроется
   */
  async prepare(id) {
    const known = this.levels.get(id);
    if (known) {
      this.setLevel(known.name, known.number);
      return;
    }

    this.setLevel('', CFG.bootLevel);

    try {
      const res = await fetch(asset(`locations/${id}.json`));
      if (!res.ok) return;

      const data = await res.json();
      this.setLevel(levelName(id, data.name), data.number ?? CFG.bootLevel);
    } catch {
      // не прочиталось — заставка просто останется с запасной картинкой
    }
  }

  /**
   * Заставку больше никто не закрывает: отсюда и считать, сколько она провисела.
   *
   * Поднимают её заранее, ещё под экраном загрузки: тот выше по слою, и в щель
   * между их уходом и её приходом иначе виден голый холст. Но пока она под ним,
   * её никто не видит — а время идёт, и к своему выходу она успевала отстоять
   * положенное и уходить сразу же. Картинки уровня при этом не видел никто.
   */
  uncovered() {
    if (this.root.hidden) return;

    this.shownAt = performance.now();

    /**
     * И полосу — с начала.
     *
     * Под экраном загрузки она ползла всё это время, и к своему выходу успевала
     * уйти почти к краю. Игрок её там не видел: открываясь, заставка показывала
     * ему чужой хвост, который тут же добегал до конца, — и весь её путь
     * сводился к короткому рывку в первый же миг.
     *
     * Ровно та же поправка, что и со временем строкой выше: и время, и полоса
     * начинают счёт тогда, когда их начинают видеть.
     */
    this.covered = false;

    /**
     * Полосу не трогаем и назад не отматываем.
     *
     * Её вела загрузка файлов, и она стоит там, где та её оставила, — на своей
     * доле. Отсюда заставка просто ведёт её дальше, к краю. Ради этого и
     * подхватываем её значение: своё, накрученное вслепую под чужим экраном,
     * было бы меньше, и полоса поехала бы назад.
     */
    this.progress = Math.max(this.progress, this.bar.share);
  }


  /** Довести полосу до конца и убрать заставку — не раньше, чем истечёт `minTime`. */
  async hide() {
    const turn = this.turn;

    clearInterval(this._timer);
    this._timer = null;

    const shown = performance.now() - this.shownAt;
    const left = Math.max(CFG.holdFull, CFG.minTime - shown);

    /**
     * Полоса доходит до края за то самое время, что заставка ещё простоит, — а
     * не рывком за десятую долю секунды, после которого стоит полной.
     *
     * Дело не в красоте. Заставка почти всегда ждёт не работу, а свой
     * `minTime`: уровень собран куда раньше. Полоса, добежавшая мгновенно,
     * оставляла игрока смотреть на полный край добрых полторы секунды — и
     * читалось это как «всё готово, а игра думает».
     */
    this.progress = 1;
    this.bar.finish(left);

    await new Promise((done) => setTimeout(done, left));
    this.bar.release(); // дальше полоса снова идёт как задано стилями

    // Пока мы выжидали, мог начаться следующий уровень — и заставка на экране
    // уже его, а не наша. Гасить её нельзя: под ней собирается сцена, и игрок
    // увидел бы её недостроенной.
    if (turn !== this.turn) return;

    this.root.hidden = true;
    this.bar.hide(); // полоса общая, и уходит она вместе с последним экраном

    // Вуаль растворяется сама, стилями: уровень проступает из темноты. Кадр на
    // то, чтобы браузер успел заметить её чёрной, — иначе переходу не с чего
    // начинаться, и она пропадёт рывком.
    requestAnimationFrame(() => this.veil.classList.remove('veil--black'));
  }

}
