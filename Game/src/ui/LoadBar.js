/**
 * Полоса загрузки — одна на всю игру.
 *
 * Раньше их было две: своя у экрана загрузки и своя у заставки уровня. Выглядели
 * они одинаково, стояли в одном и том же месте экрана, и игрок честно принимал
 * их за одну — но это были разные полосы, и в миг пересменки первая исчезала
 * вместе со своим экраном, а вторая показывалась с тем значением, до которого
 * успела доползти, пока её никто не видел. Со стороны полоса на мгновение
 * проскальзывала.
 *
 * Лечить это подгонкой значений друг под друга бессмысленно: пока полос две, их
 * всегда можно рассинхронизировать. Поэтому полоса теперь и правда одна —
 * отдельный слой поверх обоих экранов, ровно в той же точке, где стояли обе.
 * Экраны под ней сменяют друг друга, а она просто продолжает идти.
 *
 * Своё значение она не считает и ничего не решает: и загрузка файлов, и сборка
 * уровня сообщают ей долю сами. Её дело — показать.
 */
export class LoadBar {
  constructor(container = document.body) {
    this.root = document.createElement('div');
    this.root.className = 'loadbar';
    this.root.hidden = true;

    this.fill = document.createElement('div');
    this.fill.className = 'loadbar__fill';
    this.root.appendChild(this.fill);
    container.appendChild(this.root);

    this.share = 0;
  }

  /**
   * Показать полосу.
   *
   * @param {number} [from] — с какой доли начать. Ставится без перехода: полоса
   *   должна возникнуть на своём месте, а не приехать туда на глазах.
   */
  show(from = 0) {
    // Уже идёт — не трогаем. Заставку уровня поднимают ещё под экраном
    // загрузки, и её показ не должен обнулять то, что полоса уже прошла.
    if (!this.root.hidden) return;

    this.root.hidden = false;
    this.set(from, true);
  }

  hide() {
    this.root.hidden = true;
  }

  /**
   * Поставить долю.
   *
   * @param {number} share — от нуля до единицы
   * @param {boolean} [now] — без перехода. Нужно там, где полосу отматывают
   *   назад: переход отыграл бы это сползанием, а назад она ехать не должна
   *   ни при каких обстоятельствах.
   */
  set(share, now = false) {
    this.share = Math.min(1, Math.max(0, share));

    if (!now) {
      this.fill.style.width = `${Math.round(this.share * 100)}%`;
      return;
    }

    const kept = this.fill.style.transitionDuration;
    this.fill.style.transitionDuration = '0s';
    this.fill.style.width = `${Math.round(this.share * 100)}%`;

    // Обращение к размеру заставляет браузер принять новую ширину немедленно,
    // пока переход ещё снят. Без этого обе правки слились бы в одну, и переход
    // всё равно отыграл бы сползание.
    void this.fill.offsetWidth;
    this.fill.style.transitionDuration = kept;
  }

  /**
   * Довести до края за отведённое время.
   *
   * Заставка почти всегда ждёт не работу, а свой положенный срок: уровень
   * собран куда раньше. Полоса, добежавшая до края мгновенно, оставляла бы
   * игрока смотреть на полную полосу — а это читается как «всё готово, а игра
   * думает». Пусть лучше идёт ровно столько, сколько ещё стоять экрану.
   *
   * @param {number} ms
   */
  finish(ms) {
    this.fill.style.transitionDuration = `${Math.round(ms)}ms`;
    this.set(1);
  }

  /** Вернуть переход, заданный стилями: дальше полоса идёт как обычно. */
  release() {
    this.fill.style.transitionDuration = '';
  }
}
