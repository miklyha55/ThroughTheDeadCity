import { Location } from './Location.js';
import { levelName } from '../core/i18n.js';
import { asset } from '../core/paths.js';

/**
 * Загружает локации по JSON и переключает их: старая снимается со сцены,
 * новая строится и персонаж ставится в её точку старта.
 */
export class LocationManager {
  constructor(scene, prefabs, player, zombies) {
    this.scene = scene;
    this.prefabs = prefabs;
    this.zombies = zombies;
    this.player = player;
    this.current = null;
    this.loading = false;
    this.onChange = null; // после смены локации — обновить HUD и прочее
    this.onOpened = null; // уровень открылся: заставка ушла, мир пошёл
    this.editing = false; // в режиме правки статику не сливаем: её двигают мышью
    this.camera = null;   // ставится снаружи: её надо переносить вместе с игроком
    this.splash = null;   // заставка на время загрузки; ставится снаружи
    this.onFinish = null; // цепочка кончилась: игра пройдена
    this.sfx = null;      // голоса зомби; тоже ставится снаружи
    this.seeThrough = null; // просвечивание заслонивших зданий
  }

  /** Подменяет библиотеку префабов и пересобирает текущую локацию на свежих моделях. */
  async useLibrary(prefabs) {
    this.prefabs = prefabs;
    if (this.current) await this.load(this.current.data.id);
  }

  /** Следующая локация по цепочке, куда ведёт выход текущей. */
  get nextId() { return this.current?.data.next ?? null; }

  /**
   * Переход через выход: срабатывает один раз, пока предыдущая загрузка не закончилась.
   *
   * За последним уровнем следующего нет — там кончается не цепочка, а игра,
   * поэтому пустой `next` это не тупик, а сигнал наружу.
   */
  advance() {
    // Пока висит итог уровня, выход уже пройден: герой стоит в проёме, и без
    // этой проверки каждый кадр засчитывал бы уровень заново.
    if (this.loading || this.holding) return;

    // Уровень засчитывается пройденным здесь, а не на входе в следующий: выход
    // — единственное место, где это точно случилось, и последний уровень
    // цепочки засчитывается так же, как все прочие.
    const id = this.current?.data?.id;
    this.onPassed?.(id);

    if (!this.nextId) {
      this.onFinish?.();
      return;
    }

    // Между уровнями — итог пройденного. Следующий грузится, только когда игрок
    // сам нажмёт «Продолжить»; без экрана итога — сразу, как раньше.
    const next = this.nextId;
    if (this.onLevelDone) {
      this.holding = true;
      this.onLevelDone(id, () => {
        this.holding = false;
        this.load(next);
      });
      return;
    }
    this.load(next);
  }

  async load(id) {
    this.holding = false; // любая загрузка снимает ожидание итога: уровень уже другой
    // Вторая загрузка поверх идущей рушит обе: та, что пришла первой, уже
    // разобрала прежний мир, а вторая соберёт свой и затрёт её работу. Такое
    // бывает от двойного нажатия — на экране смерти или на карте уровней.
    if (this.loading) return null;

    this.loading = true;
    // Уровень уходит: мир встаёт до самой сборки нового. Куда именно идём —
    // тоже говорим: тот же уровень заново и переход на другой это разные вещи,
    // и снаружи их надо различать.
    this.onLoading?.(id);
    this.sfx?.silence(); // старый уровень уходит — его шаги и хрипы уходят с ним

    /**
     * Сначала — чем встречать, и только потом показ.
     *
     * Ждём по-настоящему, а не пускаем вдогонку: заставка обязана открыться уже
     * с картинкой. Показанная раньше, она первые мгновения стоит чёрной, и
     * полоса на пустом чёрном читается как отдельная, первая загрузка — а следом
     * будто начинается вторая, уже с картинкой. Это одна и та же.
     *
     * Пока ждём, на экране висит прежний уровень, и это лучше черноты.
     */
    await this.splash?.prepare(id);
    this.splash?.show();

    let opened = null;

    try {
      opened = await this._load(id);
      return opened;
    } finally {
      // Уровень начинается, когда заставка УЖЕ ушла, а не когда собрана сцена.
      //
      // Порядок тут был обратный, и это ломало игру на каждом переходе. Сборка
      // уровня быстрая — всё нужное давно в памяти, — а заставка висит своё
      // время, около двух секунд. В эту щель мир уже жил: персонаж набивал
      // магазин, зомби шли к нему, а игрок смотрел на картинку и ничего не мог.
      // Случалось и вовсе прийти на уровень уже избитым.
      //
      // Теперь наоборот: пока картинка на экране, мир стоит. Полоса на ней всё
      // равно декоративная — она отмеряет не работу, а время показа, — вот по
      // её концу уровень и начинается.
      await this.splash?.hide();
      this.loading = false;

      /**
       * Экран свободен, мир пошёл — вот теперь уровню и можно заговорить.
       * Всё, что должно случиться на глазах у игрока, а не под картинкой,
       * вешается сюда.
       *
       * Но только если уровень и правда собрался. Раньше это стояло в `finally`
       * без оговорок, и на сорванной загрузке — нет файла, оборвалась сеть —
       * открытым объявлялся тот уровень, что был до: на первом это падение на
       * пустоте, на остальных игра оживала на прежнем месте, и круг выхода тут
       * же отправлял её на ту же сорванную загрузку по кругу.
       */
      if (opened) this.onOpened?.(opened);
    }
  }

  async _load(id) {
    const res = await fetch(asset(`locations/${id}.json`));
    if (!res.ok) throw new Error(`локация «${id}» не найдена (${res.status})`);
    const data = await res.json();
    // Для знакомого уровня это уже сделано до показа; здесь — на случай, если он
    // открыт в обход цепочки и о нём узнали только сейчас, из файла.
    // Название на языке игры: в файле оно записано по-русски, и править файл
    // нельзя — его перезаписывает правка расстановки.
    this.splash?.setLevel(levelName(id, data.name), data.number ?? 1);

    this.current?.dispose();
    this.seeThrough?.clear(); // прежние здания ушли вместе с локацией
    this.current = null;      // прежнего мира больше нет: на него нельзя ссылаться

    const location = new Location(
      data, this.prefabs, this.zombies, this.player?.blood,
      { batched: !this.editing, sfx: this.sfx, seeThrough: this.seeThrough }
    );
    this.scene.add(location.group);
    this.current = location;

    this.player.placeAt(location.spawn, location.spawnYaw);
    this.camera?.snap(); // кадр готов сразу: перелёта через всю карту не будет
    this.onChange?.(location);
    return location;
  }
}
